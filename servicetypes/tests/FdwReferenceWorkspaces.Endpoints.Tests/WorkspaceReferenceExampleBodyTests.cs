    // The example the workspace reference offers for the data set's query, read from the document the reference serves, with
    // the members its body schema declares and the ones it requires, gathered through $ref and allOf.
    private async Task<(JsonObject Example, BodySchema Schema)> Example()
    {
        var document = await Document();
        var body = document["paths"]![$"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/{WorkspaceName}/{DataSetName}"]!["post"]!
            ["requestBody"]!["content"]!["application/json"]!;
        var schema = new BodySchema();
        schema.Read(body["schema"], document["components"]?["schemas"]);
        return (body["example"]!.AsObject(), schema);
    }

    // The workspace reference document the host serves, as the signed-in caller reads it.
    private async Task<JsonNode> Document()
    {
        using var request = new HttpRequestMessage(
            HttpMethod.Get, new Uri($"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/openapi/data/{WorkspaceName}", UriKind.Relative));
        request.Headers.Add(HeaderScheme.Header, "signed-in");
        using var response = await _client.SendAsync(request, TestContext.Current.CancellationToken);
        var json = await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken);
        response.StatusCode.ShouldBe(HttpStatusCode.OK, json);

        return JsonNode.Parse(json)!;
    }

    private async Task<HttpResponseMessage> Post(string body)
    {
        using var request = new HttpRequestMessage(
            HttpMethod.Post, new Uri($"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/{WorkspaceName}/{DataSetName}", UriKind.Relative))
        {
            Content = new StringContent(body, Encoding.UTF8, "application/json"),
        };
        request.Headers.Add(HeaderScheme.Header, "signed-in");
        return await _client.SendAsync(request, TestContext.Current.CancellationToken);
    }

    private sealed class BodySchema
    {
        public HashSet<string> Properties { get; } = new(StringComparer.OrdinalIgnoreCase);

        public HashSet<string> Required { get; } = new(StringComparer.OrdinalIgnoreCase);

        public void Read(JsonNode? schema, JsonNode? components)
        {
            if (schema is not JsonObject described)
                return;

            if (described["$ref"] is JsonValue reference && components is not null)
                Read(components[reference.GetValue<string>().Split('/')[^1]], components);

            if (described["allOf"] is JsonArray parts)
            {
                foreach (var part in parts)
                    Read(part, components);
            }

            if (described["properties"] is JsonObject properties)
                Properties.UnionWith(properties.Select(property => property.Key));

            if (described["required"] is JsonArray required)
                Required.UnionWith(required.Select(name => name!.GetValue<string>()));
        }
    }

    /// <summary>Authenticates a caller carrying the permissions named in one header; no header, no identity.</summary>
    private sealed class HeaderScheme(
        IOptionsMonitor<AuthenticationSchemeOptions> options, ILoggerFactory logger, UrlEncoder encoder)
        : AuthenticationHandler<AuthenticationSchemeOptions>(options, logger, encoder)
    {
        public const string Name = "Test";
        public const string Header = "X-Test-Permissions";

        protected override Task<AuthenticateResult> HandleAuthenticateAsync()
        {
            if (!Request.Headers.TryGetValue(Header, out var permissions))
                return Task.FromResult(AuthenticateResult.NoResult());

            var identity = new ClaimsIdentity(
                permissions.ToString().Split(',').Select(p => new Claim("perm", p.Trim())), Name);
            return Task.FromResult(AuthenticateResult.Success(new AuthenticationTicket(new ClaimsPrincipal(identity), Name)));
        }
    }
