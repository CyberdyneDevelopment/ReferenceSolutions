/// <summary>
/// FDW-1125: the example body a workspace's API reference offers for a data set's query holds only the body's required
/// members -- none, so <c>{}</c> -- and the query route accepts it, so "Send" in the reference works as it is.
/// </summary>
/// <remarks>
/// The real pipeline end to end: the OpenAPI document is generated by FastEndpoints and NSwag as the host generates it, cut by
/// the workspace reference endpoint, and the example it offers for <c>POST /api/v1/Sales/NflTeams</c> is posted to the real
/// query endpoint. The configuration providers, the access policy and the gateway are the only stand-ins.
/// </remarks>
public sealed class WorkspaceReferenceExampleBodyTests : IAsyncLifetime
{
    private const string WorkspaceName = "Sales";
    private const string DataSetName = "NflTeams";
    private const string VariationName = "AfcEast";
    private static readonly Guid DataSetId = Guid.Parse("6f1c2d3e-4b5a-4c6d-8e7f-90a1b2c3d4e5");

    private readonly Mock<IDataGateway> _gateway = new();
    private WebApplication _app = null!;
    private HttpClient _client = null!;

    public async ValueTask InitializeAsync()
    {
        var builder = WebApplication.CreateBuilder();
        builder.Logging.ClearProviders();
        builder.WebHost.UseTestServer();
        builder.Services
            .AddAuthentication(HeaderScheme.Name)
            .AddScheme<AuthenticationSchemeOptions, HeaderScheme>(HeaderScheme.Name, _ => { });
        builder.Services.AddAuthorization();
        builder.Services.AddFastEndpoints(o =>
        {
            o.Assemblies = [typeof(QueryWorkspaceDataSetEndpoint).Assembly];
            o.DisableAutoDiscovery = true;
            o.Filter = t => t == typeof(QueryWorkspaceDataSetEndpoint) || t == typeof(WorkspaceReferenceDocumentEndpoint);
        });
        builder.Services.SwaggerDocument(o =>
        {
            o.AutoTagPathSegmentIndex = 0;
            o.DocumentSettings = s =>
            {
                s.DocumentName = FdwReferenceEndpoints.Endpoints.OpenApiDocumentName;
                s.OperationProcessors.Add(new AuthorizationMetadataOperationProcessor());
            };
        });

        var dataSet = NflTeams();
        var workspace = Mock.Of<IWorkspaceImplementationConfiguration>(d =>
            d.Name == WorkspaceName
            && d.Resources == new List<WorkspaceResourceConfiguration>
            {
                new() { Name = DataSetName, ResourceType = "DataSet", ResourceId = DataSetId },
            });

        var workspaces = new Mock<IWorkspaceConfigurationProvider>();
        workspaces.Setup(d => d.Get(WorkspaceName, It.IsAny<CancellationToken>()))
            .ReturnsAsync(GenericResult<IWorkspaceImplementationConfiguration>.Success(workspace));
        builder.Services.AddSingleton(workspaces.Object);

        var access = new Mock<IWorkspaceAccessPolicy>();
        access.Setup(a => a.MayRead(workspace, It.IsAny<CancellationToken>())).ReturnsAsync(GenericResult.Success());
        builder.Services.AddSingleton(access.Object);

        var dataSets = new Mock<IDataSetConfigurationProvider>();
        dataSets.Setup(d => d.Get(DataSetId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(GenericResult<IDataSetImplementationConfiguration>.Success(dataSet));
        builder.Services.AddSingleton(dataSets.Object);

        var reads = new Mock<IWorkspaceReadService>();
        reads.Setup(r => r.DataSet(WorkspaceName, DataSetName, It.IsAny<CancellationToken>()))
            .ReturnsAsync(GenericResult<ReadableDataSet>.Success(new ReadableDataSet(DataSetName, dataSet, [])));
        // What the data route serves in the workspace: the attached data set and a variation of it the workspace owns.
        reads.Setup(r => r.DataSets(It.IsAny<IWorkspaceImplementationConfiguration>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(GenericResult<IReadOnlyList<ReadableDataSet>>.Success(
                new List<ReadableDataSet>
                {
                    new(DataSetName, dataSet, []),
                    new(VariationName, dataSet, ["{\"field\":\"Team\",\"operator\":\"Equal\",\"value\":\"Patriots\"}"]),
                }));
        builder.Services.AddSingleton(reads.Object);

        builder.Services.AddSingleton(Mock.Of<ISystemRoleConfiguration>());

        _gateway
            .Setup(g => g.Execute<IEnumerable<Dictionary<string, object?>>>(It.IsAny<IDataCommand>(), It.IsAny<DataSetTarget>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(GenericResult<IEnumerable<Dictionary<string, object?>>>.Success(
                [new Dictionary<string, object?> { ["Notes"] = "AFC East", ["Team"] = "Patriots", ["Wins"] = 14 }]));
        var gateways = new Mock<IDataGatewayProvider>();
        gateways.Setup(g => g.ByName("Main")).Returns(_gateway.Object);
        builder.Services.AddSingleton(gateways.Object);

        var settings = new Mock<IEffectiveSettingsProvider>();
        settings.Setup(s => s.GetEffectiveValue<int>(SettingDefinitions.DefaultPaginationSize, It.IsAny<Guid?>(), It.IsAny<string?>())).Returns(25);
        settings.Setup(s => s.GetEffectiveValue<int>(SettingDefinitions.MaxPaginationSize, It.IsAny<Guid?>(), It.IsAny<string?>())).Returns(1000);
        settings.Setup(s => s.GetEffectiveValue<int>(SettingDefinitions.MaxCalculatedFilterRows, It.IsAny<Guid?>(), It.IsAny<string?>())).Returns(10000);
        builder.Services.AddSingleton(settings.Object);

        _app = builder.Build();
        _app.UseAuthentication();
        _app.UseAuthorization();
        _app.UseFastEndpoints(c => c.Endpoints.RoutePrefix = FdwReferenceEndpoints.Endpoints.RoutePrefix);
        await _app.StartAsync(TestContext.Current.CancellationToken);
        _client = _app.GetTestClient();
    }

    public async ValueTask DisposeAsync()
    {
        _client.Dispose();
        await _app.StopAsync();
        await _app.DisposeAsync();
    }

    [Fact]
    [Trait("Priority", "P0")]
    public async Task TheGeneratedExampleBodyIsAcceptedByTheQueryEndpointExactlyAsOffered()
    {
        var (example, _) = await Example();

        var response = await Post(example.ToJsonString());

        response.StatusCode.ShouldBe(
            HttpStatusCode.OK, await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken));
    }

    // The query body has no required member, so the example is the empty object: no optional member, not even as null.
    [Fact]
    public async Task TheGeneratedExampleHoldsOnlyTheRequiredMembersWhichIsNone()
    {
        var (example, _) = await Example();

        example.ToJsonString().ShouldBe("{}");
    }

    [Fact]
    public async Task TheOptionalMembersStayInTheSchemaAndAreNotRequired()
    {
        var (_, schema) = await Example();

        foreach (var member in new[] { "filter", "sort", "skip", "take" })
        {
            schema.Properties.ShouldContain(member);
            schema.Required.ShouldNotContain(member);
        }
    }

    [Fact]
    public async Task ABodyWithAValidFilterGroupAndTakeIsAccepted()
    {
        var response = await Post(
            "{\"take\":5,\"filter\":{\"logic\":\"And\",\"nodes\":[{\"field\":\"Team\",\"operator\":\"Equal\",\"value\":\"Patriots\"}]}}");

        response.StatusCode.ShouldBe(
            HttpStatusCode.OK, await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken));
    }

    [Fact]
    public async Task ABodyOfNullsReadsAsOneThatLeftEveryMemberOut()
    {
        var response = await Post("{\"filter\":null,\"sort\":null,\"skip\":null,\"take\":null}");

        response.StatusCode.ShouldBe(
            HttpStatusCode.OK, await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken));
    }

    [Fact]
    public async Task AFilterGroupWithNoLogicAndANullNodeIsRefusedNamingTheMember()
    {
        var response = await Post(
            "{\"filter\":{\"logic\":null,\"nodes\":[null],\"field\":null,\"operator\":null,\"value\":null},\"take\":1}");

        response.StatusCode.ShouldBe(HttpStatusCode.BadRequest);
        (await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken)).ShouldContain("filter.logic");
    }

    // FDW-1318: the reference lists every name the data route serves in the workspace, a variation the workspace owns included.
    [Fact]
    [Trait("Priority", "P0")]
    public async Task TheReferenceListsAVariationTheWorkspaceOwnsUnderItsOwnName()
    {
        var document = await Document();

        var paths = document["paths"]!.AsObject().Select(p => p.Key).ToList();
        paths.ShouldContain($"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/{WorkspaceName}/{DataSetName}");
        paths.ShouldContain($"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/{WorkspaceName}/{VariationName}");
    }

    [Fact]
    [Trait("Priority", "P0")]
    public async Task AVariationIsDescribedAsAVariationWithTheFieldsOfTheDataSetItVaries()
    {
        var document = await Document();

        var operation = document["paths"]![$"/{FdwReferenceEndpoints.Endpoints.RoutePrefix}/{WorkspaceName}/{VariationName}"]!["post"]!;
        operation["summary"]!.GetValue<string>().ShouldBe($"Query {VariationName}");
        var description = operation["description"]!.GetValue<string>();
        description.ShouldContain($"**{VariationName}**");
        description.ShouldContain($"variation of the **{DataSetName}** data set");
        description.ShouldContain("`Team`");
    }

